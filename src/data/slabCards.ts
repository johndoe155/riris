/**
 * Wrap an externally loaded NFT (Alchemy fetch or a local upload) as a slab so
 * the Forge can render it through the same layered model.
 */
export function cardFromNft(
  nft: { image: string | null; name: string; collection: string; tokenId: string; contract: string },
  style: FinishName
): SlabCard {
  const base = slabCards[0];
  const image = nft.image;
  return {
    ...base,
    id: `nft-${nft.tokenId}`,
    art: image ?? base.art,
    title: `${(nft.name || 'Unknown').toUpperCase()}`,
    collection: nft.collection || 'Custom',
    style,
    grade: '10',
    serial: `${nft.tokenId}/—`,
    handle: nft.contract ? `${nft.contract.slice(0, 6)}…${nft.contract.slice(-4)}` : '@owner',
  };
}

